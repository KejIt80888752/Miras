import { useState } from 'react'
import { createPortal } from 'react-dom'
import { useStore } from '../store'
import { fmtDate, qtyFmt } from '../utils'
import { Modal } from './ui'

export function Invoice({ b }) {
  const { db, money } = useStore()
  const s = db.settings
  const isOut = b.type === 'out'
  const party = db.parties.find((p) => p.id === b.partyId)
  return (
    <div className="inv">
      <div className="top">
        <div>
          <h3>{s.bizName}</h3>
          <div className="muted" style={{ whiteSpace: 'pre-line' }}>
            {s.address}
            {s.phone && <><br />Ph: {s.phone}</>}
            {s.email && <><br />{s.email}</>}
            {s.gstin && <><br />GSTIN: {s.gstin}</>}
          </div>
        </div>
        <div style={{ textAlign: 'right' }}>
          <h3>{isOut ? 'INVOICE' : 'PURCHASE BILL'}</h3>
          <div><b>{b.no}</b></div>
          <div className="muted">Date: {fmtDate(b.date)}</div>
        </div>
      </div>
      <div style={{ marginBottom: 14 }}>
        <div className="muted">{isOut ? 'Bill to' : 'Supplier'}</div>
        <b>{b.partyName}</b>
        {party?.phone && <><br />{party.phone}</>}
        {party?.address && <><br />{party.address}</>}
      </div>
      <table>
        <thead><tr><th>#</th><th>Item</th><th className="n">Qty</th><th className="n">Rate</th><th className="n">Amount</th></tr></thead>
        <tbody>
          {b.items.map((l, i) => (
            <tr key={i}><td>{i + 1}</td><td>{l.name}</td><td className="n">{qtyFmt(l.qty)} {l.unit}</td><td className="n">{money(l.rate)}</td><td className="n">{money(l.qty * l.rate)}</td></tr>
          ))}
        </tbody>
      </table>
      <div className="tot">
        <div><span>Subtotal</span><span>{money(b.sub)}</span></div>
        {!!b.discount && <div><span>Discount</span><span>− {money(b.discount)}</span></div>}
        {!!b.tax && <div><span>Tax ({b.tax}%)</span><span>{money(b.taxAmt)}</span></div>}
        <div className="g"><span>Total</span><span>{money(b.total)}</span></div>
      </div>
      {b.note && <p className="muted" style={{ marginTop: 14 }}>Note: {b.note}</p>}
      <p className="muted" style={{ textAlign: 'center', marginTop: 28 }}>Thank you! · Generated by Miras</p>
    </div>
  )
}

export function InvoiceModal({ bill, onClose }) {
  const [printing, setPrinting] = useState(false)
  const print = () => {
    setPrinting(true)
    document.body.classList.add('printing')
    setTimeout(() => {
      const done = () => { document.body.classList.remove('printing'); setPrinting(false); window.removeEventListener('afterprint', done) }
      window.addEventListener('afterprint', done)
      window.print()
      setTimeout(done, 500)
    }, 50)
  }
  return (
    <>
      <Modal title={bill.no} onClose={onClose} wide
        footer={<><button className="btn" onClick={onClose}>Close</button><button className="btn primary" onClick={print}>🖨 Print</button></>}>
        <Invoice b={bill} />
      </Modal>
      {printing && createPortal(<div id="printArea"><Invoice b={bill} /></div>, document.body)}
    </>
  )
}
